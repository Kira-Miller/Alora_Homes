export function t(key, lang = 'ru') {
  const dict = DICT[lang] || DICT.ru;
  return dict[key] || DICT.ru[key] || key;
}

export function pluralObjects(count, lang = 'ru') {
  if (lang === 'en') {
    return count === 1 ? t('objectsWord1', 'en') : t('objectsWord5', 'en');
  }
  const mod100 = count % 100;
  const mod10 = count % 10;
  if (mod100 >= 11 && mod100 <= 14) return t('objectsWord5', 'ru');
  if (mod10 === 1) return t('objectsWord1', 'ru');
  if (mod10 >= 2 && mod10 <= 4) return t('objectsWord2', 'ru');
  return t('objectsWord5', 'ru');
}

export function pluralFloors(count, lang = 'ru') {
  const n = Math.abs(Number(count)) || 0;
  if (lang === 'en') {
    return n === 1 ? t('floorWord1', 'en') : t('floorWord5', 'en');
  }
  const mod100 = n % 100;
  const mod10 = n % 10;
  if (mod100 >= 11 && mod100 <= 14) return t('floorWord5', 'ru');
  if (mod10 === 1) return t('floorWord1', 'ru');
  if (mod10 >= 2 && mod10 <= 4) return t('floorWord2', 'ru');
  return t('floorWord5', 'ru');
}

/**
 * Форматирует цену в основной и дополнительной валютах (BYN / USD)
 */
export function formatPrices(priceByn, priceUsd, currency = 'BYN') {
  const fmtByn = `${Number(priceByn).toLocaleString('ru-RU')} BYN`;
  const fmtUsd = `$${Number(priceUsd).toLocaleString('ru-RU')}`;
  if (currency === 'USD') {
    return {primary: fmtUsd, secondary: fmtByn};
  }
  return {primary: fmtByn, secondary: fmtUsd};
}

/**
 * Применяет переводы ко всем статическим элементам DOM с data-i18n
 */
export function applyStaticTranslations(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      el.textContent = t(key, lang);
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key && 'placeholder' in el) {
      el.placeholder = t(key, lang);
    }
  });
}
